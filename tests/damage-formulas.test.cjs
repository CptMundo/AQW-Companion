"use strict";
const assert=require("node:assert/strict");
require("../js/damage-formulas.js");
const F=globalThis.AQWCombatFunctions;
const stats={attackPower:785,spellPower:200};
assert.equal(F.evaluateFunction("AP1",stats),163.5);
assert.equal(F.evaluateFunction("SP1",stats),105);
assert.equal(F.evaluateFunction("AP2",stats,1),327);
assert.equal(F.evaluateFunction("SP2",stats,1),210);
const loo=F.evaluateSkill({className:"Lord of Order",skillId:"blessing",...stats});
assert.equal(loo.status,"community-base-component-only");
assert.equal(loo.damage,152.25);
assert.ok(loo.missing.includes("crit and crit damage"));
const vhl=F.evaluateSkill({className:"Void Highlord",skillId:"armageddon",...stats});
assert.equal(vhl.status,"missing-mapping");
assert.equal(vhl.damage,null);
assert.throws(()=>F.evaluateFunction("AP1",{attackPower:-1,spellPower:200}),/nonnegative/);
assert.throws(()=>F.evaluateFunction("AP2",stats,-2),/nonnegative/);
console.log("Damage formula research tests passed");
