"use strict";
const assert=require("node:assert/strict");
require("../js/damage-kernel.js");
const K=globalThis.AQWDamageKernel;
const items=[{category:"all",percent:51},{category:"undead",percent:50}];
assert.equal(K.gearMultiplier({items,monsterType:"undead"}).multiplier,2.265);
assert.equal(K.gearMultiplier({items,monsterType:"chaos"}).multiplier,1.51);
assert.equal(K.gearMultiplier({items,monsterType:"undead",kind:"dot"}).multiplier,1);
assert.equal(K.gearMultiplier({items:[{category:"all",percent:10},{category:"all",percent:25}]}).multiplier,1.25);
assert.equal(K.gearMultiplier({items:[{category:"dragon",percent:50}],monsterType:"dragonkin"}).multiplier,1.5);
assert.equal(K.expectedDirectHit({baseComponent:100}).expected,null);
const hit=K.expectedDirectHit({mappingVerified:true,baseComponent:100,critChancePct:25,critMultiplierPct:200,hitChancePct:100});
assert.equal(hit.expected,125);
assert.equal(hit.status,"unvalidated-model");
const crit=K.expectedDirectHit({mappingVerified:true,baseComponent:100,alwaysCrit:true,neverMiss:true,critMultiplierPct:250});
assert.equal(crit.expected,250);
const miss=K.expectedDirectHit({mappingVerified:true,baseComponent:100,hitChancePct:50});
assert.equal(miss.expected,50);
assert.throws(()=>K.gearMultiplier({items:[{category:"all",percent:NaN}]}),/finite/);
assert.throws(()=>K.gearMultiplier({monsterType:"unknown"}),/unknown monster tag/);
assert.throws(()=>K.expectedDirectHit({mappingVerified:true,baseComponent:-1}),/finite/);
console.log("Damage kernel tests passed");
