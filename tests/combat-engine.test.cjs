"use strict";
const assert=require("node:assert/strict");
require("../js/combat-engine.js");
const engine=globalThis.AQWCombatEngine;
const base={seconds:60,rotation:["unshackle","gaze","armageddon"],actionGapSeconds:0.5};
const timeline=engine.simulate(base);
assert.equal(timeline.seconds,60);
assert.equal(timeline.fullDamage,null);
assert.equal(timeline.dps,null);
assert.ok(timeline.missingHitCount>0);
assert.equal(timeline.events[0].id,"unshackle");
assert.ok(timeline.events.some(e=>e.id==="armageddon"&&e.time>=15));
for(const event of timeline.events) assert.ok(event.time>=0&&event.time<60);
const replay=engine.simulate({...base,measuredHits:{unshackle:100,gaze:200,armageddon:300}});
assert.equal(replay.resultStatus,"measured-input-only");
assert.equal(replay.missingHitCount,0);
assert.equal(replay.fullDamage,replay.events.reduce((sum,e)=>sum+e.damage,0));
assert.equal(replay.dps,replay.fullDamage/60);
assert.throws(()=>engine.simulate({...base,seconds:20}),/fixed 60-second/);
assert.throws(()=>engine.simulate({...base,rotation:["wrong"]}),/Unknown skill/);
assert.throws(()=>engine.simulate({...base,measuredHits:{unshackle:-2}}),/nonnegative/);
const withAutos=engine.simulate({...base,includeAuto:true});
assert.ok(withAutos.events.some(e=>e.kind==="auto"));
assert.equal(withAutos.dps,null);
const observed=engine.simulate({seconds:60,observedEvents:[{time:10,id:"gaze",damage:200},{time:0,id:"unshackle",damage:100},{time:59.99,id:"dot",damage:50}]});
assert.equal(observed.resultStatus,"observed-window");
assert.equal(observed.fullDamage,350);
assert.equal(observed.dps,350/60);
assert.equal(observed.events[0].time,0);
assert.equal(engine.simulate({observedEvents:[]}).dps,null);
const universal=engine.simulate({className:"Legion Revenant",observedTotalDamage:600000});
assert.equal(universal.dps,10000);
assert.equal(universal.fullDamage,600000);
assert.equal(universal.resultStatus,"observed-total");
assert.throws(()=>engine.simulate({observedTotalDamage:-2}),/nonnegative/);
assert.throws(()=>engine.simulate({observedTotalDamage:Infinity}),/finite/);
assert.throws(()=>engine.simulate({observedEvents:[{time:60,id:"gaze",damage:100}]}),/outside/);
console.log("All combat-engine tests passed",timeline.events.length,withAutos.events.length);
