"use strict";
const assert=require("node:assert/strict");
require("../js/combat-timeline.js");
const T=globalThis.AQWCombatTimeline;
const plan=T.plan();
assert.equal(plan.status,"timeline-only");
assert.equal(plan.seconds,60);
assert.equal(plan.dps,null);
assert.equal(plan.damage,null);
assert.ok(plan.events.length>20);
assert.equal(plan.events[0].id,"unshackle");
assert.equal(plan.events[0].hastePercent,0);
assert.equal(plan.events[1].hastePercent,30);
assert.ok(plan.events.some(e=>e.id==="armageddon"&&e.time>10&&e.time<15));
assert.ok(plan.events.every(e=>e.time>=0&&e.time<60));
for(let i=1;i<plan.events.length;i++)assert.ok(plan.events[i].time>=plan.events[i-1].time);
const staticPlan=T.plan({dynamicHaste:false});
assert.equal(staticPlan.events[1].hastePercent,0);
assert.ok(staticPlan.counts.armageddon<plan.counts.armageddon);
const cap=T.plan({baseHastePercent:40});
assert.ok(cap.events.every(e=>e.hastePercent<=50));
assert.ok(cap.events.some(e=>e.hastePercent===50));
const defensive=T.plan({rotation:["shackle","gaze","armageddon"]});
assert.ok(defensive.events.some(e=>e.auras.some(a=>a.id==="shackled")));
assert.ok(!defensive.events.some(e=>e.id==="unshackle"));
const autos=T.plan({includeAuto:true});
assert.ok(autos.events.some(e=>e.type==="auto"));
assert.ok(autos.counts.contract>0);
const same=T.plan();
assert.deepEqual(plan.events,same.events);
assert.throws(()=>T.plan({seconds:20}),/60 seconds/);
assert.throws(()=>T.plan({rotation:["unverified"]}),/unknown VHL skill/);
assert.throws(()=>T.plan({actionGapSeconds:0}),/between/);
assert.throws(()=>T.plan({baseHastePercent:70}),/between/);
assert.throws(()=>T.plan({strategy:"random"}),/strategy/);
const dauntless=T.plan({weaponForge:"Dauntless"});
assert.ok(dauntless.events.some(e=>e.type==="forge-proc"&&e.id==="dauntless"));
assert.ok(dauntless.events.some(e=>e.hastePercent===50));
assert.ok(dauntless.events.some(e=>e.auras.some(a=>a.id==="dauntless")));
const valiance=T.plan({weaponForge:"Valiance"});
assert.ok(valiance.events.some(e=>e.type==="auto"));
assert.ok(valiance.events.some(e=>e.type==="forge-proc"&&e.id==="valiance"));
const ravenous=T.plan({weaponForge:"Ravenous"});
assert.ok(ravenous.events.some(e=>e.type==="forge-proc"&&e.id==="ravenous"));
const smite=T.plan({weaponForge:"Smite"});
assert.ok(smite.events.some(e=>e.type==="forge-proc"&&e.id==="smite"));
assert.ok(dauntless.events.filter(e=>e.type==="forge-proc").every(e=>e.damage===null));
assert.throws(()=>T.plan({weaponForge:"Unverified"}),/unsupported weapon Forge/);
assert.ok(plan.nominalResourceCosts.spentMaxHpPct>100);
assert.equal(plan.nominalResourceCosts.modeledSurvival,false);
assert.ok(plan.events.filter(e=>e.type==="skill").every(e=>e.insolentFoolsProcChancePct===20));
const contract=T.plan({includeAuto:true}).events.filter(e=>e.type==="auto");
assert.ok(contract.some(e=>e.conditionalEffect?.includes("Soul Breach")));
assert.ok(contract.some(e=>e.posture==="neutral"));
console.log("Combat timeline regression passed",plan.events.length,autos.events.length);
