"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const api=require("../js/wishlist-finds.js");
const s=(uid,exportedAt,importedAt,items)=>({uid,fileName:uid+".json",exportedAt,importedAt,items});
const item=(Name,ID,Type="Weapon",Bank=0)=>({Name,ID,Type,Bank,Count:1});
const old=s("old","2026-11-01T12:00:00Z","2026-11-01T13:00:00Z",[item("Alpha",1)]);
const recent=s("new","2026-11-22T12:00:00Z","2026-11-22T13:00:00Z",[item("Alpha",1, "Weapon",1),item("Celestial Copper of Destiny",2,"Misc"),item("Other",3)]);
const wishes=[{name:"Celestial Copper of Destiny",type:"Misc"},{name:"Other",type:"Armor",createdAt:"2026-11-23T00:00:00Z"}];
const original=JSON.stringify({old,recent,wishes});
const result=api.find([recent,old],wishes);
assert.equal(JSON.stringify({old,recent,wishes}),original,"Never mutate stored inventory or Wishlist");
assert.equal(result.count,1);
assert.equal(result.recent[0].name,"Celestial Copper of Destiny");
assert.equal(result.recent[0].source,"new.json");
assert.equal(result.recent[0].previousSource,"old.json");
assert.ok(result.recent[0].firstSeenAt>0);
assert.equal(api.find([old],wishes).count,0,"Initial import is not acquisition proof");
assert.equal(api.find([old,old],wishes).count,0,"Same snapshot is not a new acquisition");
assert.equal(api.find([recent,old],[]).count,0);
const withAfter=s("after","2026-11-23T12:00:00Z","2026-11-23T12:30:00Z",[item("Alpha",1),item("Celestial Copper of Destiny",2),item("Other",3)]);
const second=api.find([old,recent,withAfter],[{name:"Celestial Copper of Destiny",type:"Misc"},{name:"Other",type:"Armor",createdAt:"2026-11-22T22:00:00Z"}]);
assert.equal(second.count,1,"Previously observed item is not counted again as a recent win");
const noFuture=api.find([old,recent],[{name:"Other",createdAt:"2026-11-23T00:00:00Z"}]);
assert.equal(noFuture.count,0,"Goal created after item first observed does not retroactively win");
assert.equal(api.find([old,recent],[{name:"ALPHA"}]).count,0,"Owned before first comparison is not new");
const olderDate=s("historical","2026-10-31T11:00:00Z","2026-11-22T14:00:00Z",[item("Other",3)]);
assert.equal(api.find([old,olderDate,recent],[{name:"Other",createdAt:"2026-11-22T12:00:00Z"}]).count,0,"Old exported file imported later is not proof of recent acquisition");
const html=fs.readFileSync(path.join(__dirname,"../index.html"),"utf8");
assert.ok(html.includes("AQWWishlistFinds?.find(snapshots,unlocks)"));
assert.ok(html.includes('src="js/wishlist-finds.js"'));
assert.ok(html.includes("createdAt:new Date().toISOString()"));
new vm.Script(fs.readFileSync(path.join(__dirname,"../js/wishlist-finds.js"),"utf8"));
console.log("Wishlist finds: local snapshots, first observations, repeat imports and retroactive-goal prevention passed.");

assert.equal(api.find([old,recent,withAfter],wishes,{onlyUid:"after"}).count,0,"Do not repeat past achievements on Home");
assert.equal(api.find([old,recent,withAfter],wishes,{onlyUid:"new"}).count,1);
assert.equal(api.find([old,recent],[{name:"Alpha"}],{onlyUid:"new"}).count,0,"Bank movement is not a win");
assert.equal(api.find([old,recent],wishes,{onlyUid:"missing"}).count,0);
assert.ok(html.includes("onlyUid:latest.uid"));
assert.ok(html.includes("if(wins?.count)"));
assert.ok(html.includes("Wishlist Achievements"));
