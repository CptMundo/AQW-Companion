 function fromAcquisition(acquisition){
   const grouped=new Map();
   for(const [,entry] of acquisition||[])for(const m of entry?.methods||[]){
     if(m.type!=='Quest Reward'||!m.title||!wiki(m.url))continue;
     const freq=recurrence({name:m.title,details:m.details});if(!freq)continue;
     const id='wiki-'+slug(m.url.split('/').at(-1))+'-'+slug(m.title);
     if(!grouped.has(id))grouped.set(id,{id,name:m.title,group:m.npc||'Wiki quests',freq,join:map(m.join),packs:[],wiki:m.url,categories:[],rewards:[],targets:[],note:'Community catalog: verify availability and prerequisites in game.'});
     const t=grouped.get(id);if(entry.name&&!t.rewards.includes(entry.name))t.rewards.push(entry.name);
     for(const route of entry.questRoutes||[])if(route.quest===m.title&&route.source===m.url)for(const [name,count] of route.ingredients||[]){const label=name+' ×'+count;if(!t.targets.includes(label))t.targets.push(label)}
   }
   return [...grouped.values()].map(t=>({...t,categories:tagsFor(t.name,t.rewards,t.group,''),group:/\bultra\b/i.test(t.name)?'Ultra Boss':t.group}));
 }
